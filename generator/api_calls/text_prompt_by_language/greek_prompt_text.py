from generator.config import A1, Config


ANKI_PROMPT_PREAMBLE = """Θέλω να λειτουργήσεις ως επαγγελματίας δημιουργός καρτών Anki για μαθητές της σύγχρονης ελληνικής γλώσσας.

Βασικές αρχές:
1. Ελάχιστη πληροφορία: Η κάρτα πρέπει να είναι σύντομη, σαφής και εύκολη στην επανάληψη.
2. Απλή διατύπωση: Χρησιμοποίησε μόνο λεξιλόγιο και γραμματική κατάλληλα για το ζητούμενο επίπεδο.
3. Μία σημασία: Εξήγησε μόνο τη σημασία που ταιριάζει καλύτερα στο δοσμένο πλαίσιο.

Χρήση του πλαισίου:
- Αν το CONTEXT είναι κενό, χρησιμοποίησε την πιο συνηθισμένη καθημερινή σημασία.
- Αν υπάρχει CONTEXT, χρησιμοποίησέ το για να επιλέξεις τη σωστή σημασία.
- Το πλαίσιο μπορεί να είναι γραμμένο σε άλλη γλώσσα, αλλά η απάντηση πρέπει να είναι μόνο στα ελληνικά.

Μορφή εισόδου:
- WORD: [λέξη ή φράση]; CONTEXT: []
- WORD: [λέξη ή φράση]; CONTEXT: [προαιρετικό πλαίσιο]

Κανόνες εξόδου:
- Επέστρεψε μόνο το κείμενο της κάρτας, χωρίς τίτλους, εξηγήσεις ή μετάφραση.
- Μην εμφανίσεις τη λέξη ή τη φράση του WORD στην απάντηση.
- Απόκρυψε τη ζητούμενη λέξη με κάτω παύλες και διατήρησε τα κενά ανάμεσα στις λέξεις.
- Ο αριθμός των κάτω παυλών πρέπει να αντιστοιχεί στον αριθμό των γραμμάτων.
- Αν το WORD αρχίζει με ελληνικό άρθρο (ο, η, το, οι, τα, ένας, μία, ένα), κράτησε το άρθρο ορατό και απόκρυψε μόνο τη λέξη. Αυτό βοηθά τον μαθητή να θυμάται το γένος.
- Μη χρησιμοποιείς παράγωγα ή σύνθετα που αποκαλύπτουν εύκολα τη ζητούμενη λέξη.
- Χρησιμοποίησε φυσικές, καθημερινές προτάσεις και απόφυγε σπάνιες λέξεις ή ιδιωματισμούς.
"""


def level_rules() -> str:
    if Config.LEVEL == A1:
        return """
Επίπεδο A1:
- Γράψε 2 ή 3 πολύ σύντομες προτάσεις.
- Χρησιμοποίησε βασικό λεξιλόγιο, ενεστώτα και απλή σύνταξη.
- Κάθε πρόταση πρέπει να δίνει ένα άμεσο στοιχείο για τη σημασία.
"""
    return """
Επίπεδο A2:
- Γράψε 3 ή 4 σύντομες προτάσεις.
- Χρησιμοποίησε συχνό καθημερινό λεξιλόγιο και απλές συνδέσεις όπως «και», «αλλά», «όταν» ή «γιατί».
- Συμπερίλαβε ένα σύντομο, φυσικό παράδειγμα χρήσης.
"""


def examples() -> str:
    return """
Παραδείγματα:
WORD: [το σπίτι]; CONTEXT: []; RESULT: [Το _____ είναι ένα μέρος όπου μένουν άνθρωποι. Έχει δωμάτια, πόρτες και παράθυρα.]
WORD: [μαγειρεύω]; CONTEXT: [food]; RESULT: [Όταν _________, ετοιμάζω φαγητό. Χρησιμοποιώ υλικά, μια κατσαρόλα ή ένα τηγάνι.]
WORD: [το εισιτήριο]; CONTEXT: [bus]; RESULT: [Χρειάζομαι ένα _________ για να ταξιδέψω με το λεωφορείο. Μπορώ να το αγοράσω πριν μπω.]
"""


def get_prompt() -> str:
    return ANKI_PROMPT_PREAMBLE + level_rules() + examples()
